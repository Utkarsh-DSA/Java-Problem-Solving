/*
Question:
Write a Java program to check whether
a given number is even or odd.
*/

public class EvenOdd {
    public static void main(String[] args) {

        int num = 15;

        if (num % 2 == 0) {
            System.out.println("Even Number");
        } else {
            System.out.println("Odd Number");
        }
    }
}
